    def test_project_point_webmerc_wgs84(self):
        """
        Test to project an array of Points in Web Mercator to WGS84
        :return:
        """
        input_geometries = [
            {"x": -17568824.55, "y": 2428377.35},
            {"x": -17568456.88, "y": 2428431.352},
        ]

        # project
        project_return = geometry.project(input_geometries, 3857, 4326, gis=self.gis)

        # validate
        self.assertIsInstance(
            project_return, list, "Project did not return a list of geometries"
        )

        # validate values
        correct_geometries = [
            {"x": -157.82343617279275, "y": 21.305781607280093},
            {"x": -157.8201333369876, "y": 21.306233559873714},
        ]
        self.assertEqual(
            project_return[0]["x"],
            correct_geometries[0]["x"],
            "Project values mismatch",
        )
        self.assertEqual(
            project_return[0]["y"],
            correct_geometries[0]["y"],
            "Project values mismatch",
        )
        self.assertEqual(
            project_return[1]["x"],
            correct_geometries[1]["x"],
            "Project values mismatch",
        )
        self.assertEqual(
            project_return[1]["y"],
            correct_geometries[1]["y"],
            "Project values mismatch",
        )

    def test_get_envelope_from_point(self):
        """
        Test to project an array of Points to Envelope
        :return:
        """
        # construct Point obj - world points
        # https://www.arcgis.com/home/item.html?id=6996f03a1b364dbab4008d99380370ed
        geom_dict = {
            "x": 8327143.6735988045,
            "y": 4039683.818318914,
            "spatialReference": {"wkid": 102100, "latestWkid": 3857},
        }
        pt = Point(geom_dict)
        pt_envelope = pt.envelope

        # validate
        self.assertIsInstance(pt_envelope, Envelope)

        validation_envelope = {
            "xmin": 8327143.6735988045,
            "ymin": 4039683.818318914,
            "xmax": 8327143.6735988045,
            "ymax": 4039683.818318914,
            "spatialReference": {"wkid": 102100, "latestWkid": 3857},
        }

        self.assertEqual(pt_envelope, validation_envelope, "Envelope value is wrong")

